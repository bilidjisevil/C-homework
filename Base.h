#include <iostream>
#include <string>
#include <fstream>

using namespace std;

/*
Абстрактный базовый класс Base
Служит основой для всех транспортных средств (полиморфная иерархия).
Задает интерфейс (чисто виртуальные функции), который обязаны реализовать производные классы.
 */
class Base {
public:
    // Виртуальный деструктор необходим для корректного удаления объектов через указатели на базовый класс
    virtual ~Base() {}

    // Чисто виртуальная функция ввода данных с клавиатуры
    virtual void input() = 0;

    // Чисто виртуальная функция вывода информации об объекте на экран
    virtual void display() const = 0;

    // Чисто виртуальная функция сохранения данных объекта в файл
    virtual void save(ofstream& out) const = 0;

    // Чисто виртуальная функция загрузки данных объекта из файла
    virtual void load(ifstream& in) = 0;

    // Чисто виртуальная функция для получения строкового типа объекта (для идентификации при чтении)
    virtual string getType() const = 0;
};